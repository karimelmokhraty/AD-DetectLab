#!/usr/bin/env python3
"""
Convert every Sigma rule in detections/ into each supported SIEM's query
language, writing the results into queries/.

Everything under queries/ is GENERATED. Do not hand-edit it -- edit the Sigma
rule and re-run this script. CI regenerates and diffs, so a hand-edit to a
generated query fails the build.

Not every rule converts to every backend, and that is expected rather than a
failure: the Elasticsearch backend has no support for Sigma correlation rules,
so the volume-based BloodHound detection simply cannot be expressed there. The
coverage table written to queries/COVERAGE.md records exactly which rule
reaches which backend, so losing coverage shows up as a diff instead of
quietly disappearing.

Usage:  python tools/generate_queries.py
Exit:   0 = generated, 1 = a rule failed for a reason other than an
            unsupported backend feature
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DETECTIONS = REPO / "detections"
QUERIES = REPO / "queries"

# backend identifier, processing pipeline, output directory, file extension
TARGETS = [
    ("splunk", "splunk_windows", "splunk", "spl"),
    ("lucene", "ecs_windows", "elastic", "lucene"),
]

NOISE = ("Parsing Sigma rules",)


def convert(backend: str, pipeline: str, rule: Path) -> tuple[bool, str]:
    result = subprocess.run(
        ["sigma", "convert", "-t", backend, "-p", pipeline, str(rule)],
        capture_output=True,
        text=True,
    )
    body = "\n".join(
        line for line in (result.stdout or "").splitlines()
        if line.strip() and line.strip() not in NOISE
    ).strip()

    if result.returncode != 0 or not body:
        message = (result.stderr or body or "unknown error").strip()
        return False, " ".join(message.split())[:300]
    return True, body


def main() -> int:
    rules = sorted(DETECTIONS.glob("*.yml"))
    if not rules:
        print(f"no rules found in {DETECTIONS}", file=sys.stderr)
        return 1

    # Rebuild from scratch so a deleted rule cannot leave a stale query behind.
    if QUERIES.exists():
        shutil.rmtree(QUERIES)

    coverage: dict[str, dict[str, str]] = {r.name: {} for r in rules}
    hard_failures: list[str] = []

    for backend, pipeline, out_dir, ext in TARGETS:
        target_dir = QUERIES / out_dir
        target_dir.mkdir(parents=True, exist_ok=True)
        print(f"=== {backend} (pipeline: {pipeline}) -> queries/{out_dir}/")

        for rule in rules:
            ok, body = convert(backend, pipeline, rule)
            if ok:
                header = (
                    f"# GENERATED by tools/generate_queries.py -- do not edit.\n"
                    f"# source   : detections/{rule.name}\n"
                    f"# backend  : {backend} (pipeline: {pipeline})\n\n"
                )
                (target_dir / f"{rule.stem}.{ext}").write_text(header + body + "\n")
                coverage[rule.name][out_dir] = "yes"
                print(f"    ok          {rule.name}")
            else:
                unsupported = "not supported by backend" in body
                coverage[rule.name][out_dir] = (
                    "unsupported" if unsupported else f"ERROR: {body}"
                )
                label = "unsupported" if unsupported else "FAILED"
                print(f"    {label:<11} {rule.name}  ({body[:90]})")
                if not unsupported:
                    hard_failures.append(f"{rule.name} -> {backend}: {body}")
        print()

    # Coverage table, version-controlled so a regression shows up as a diff.
    names = [d[2] for d in TARGETS]
    lines = [
        "# Backend coverage",
        "",
        "GENERATED by `tools/generate_queries.py` -- do not edit.",
        "",
        "`unsupported` means the backend has no way to express that rule (for",
        "example Elasticsearch cannot represent Sigma correlation rules). That",
        "is a real limitation of the target, not a broken rule.",
        "",
        "| rule | " + " | ".join(names) + " |",
        "|---|" + "---|" * len(names),
    ]
    for rule_name in sorted(coverage):
        row = " | ".join(coverage[rule_name].get(n, "-") for n in names)
        lines.append(f"| `{rule_name}` | {row} |")
    (QUERIES / "COVERAGE.md").write_text("\n".join(lines) + "\n")

    print("=" * 72)
    if hard_failures:
        print(f"{len(hard_failures)} conversion failure(s) that are NOT backend limits:\n")
        for failure in hard_failures:
            print(f"  - {failure}")
        return 1

    print(f"Generated queries for {len(rules)} rules across {len(TARGETS)} backends.")
    print("Coverage table: queries/COVERAGE.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
